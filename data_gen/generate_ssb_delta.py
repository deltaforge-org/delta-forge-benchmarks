"""Generate the Star Schema Benchmark fixture as plain Delta tables.

SSB (O'Neil et al., 2009) is TPC-H reshaped into a 5-table star:

    lineorder  (fact, derived from TPC-H lineitem JOIN orders)
    date       (date dimension over the 7-year TPC-H range)
    part       (1:1 with TPC-H part, plus the SSB-specific p_category)
    supplier   (1:1 with TPC-H supplier, plus s_city / s_nation / s_region)
    customer   (1:1 with TPC-H customer, plus c_city / c_nation / c_region)

Output: /workspace/data/ssb_sf{scale}_delta/<table>/. Same plain Delta
protocol as generate_tpch_delta.py (no DV / no column-mapping / no row
tracking) so DuckDB's read-only delta extension can read them.

Source: this script READS the TPC-H plain Delta tables generated by
data_gen/generate_tpch_delta.py at /workspace/data/tpch_sf{scale}_delta/
and WRITES the 5 SSB tables. Run generate_tpch_delta.py first.

The SSB-from-TPCH derivation is the same one cited in the SSB paper
(Section 4) and used by every published cloud SSB-on-Delta dataset.

Usage (inside the bench container):
    python data_gen/generate_ssb_delta.py --scale 1
    python data_gen/generate_ssb_delta.py --scale 10 --overwrite
"""
from __future__ import annotations

import argparse
import shutil
import sys
import time
from pathlib import Path

# Repo root resolved from this file so the benchmark runs on any host (not just
# the container's /workspace WORKDIR). data_gen/<file>.py -> parent.parent.
_REPO_ROOT = Path(__file__).resolve().parent.parent


SSB_TABLES = ["date", "part", "supplier", "customer", "lineorder"]


# SQL deriving each SSB table from the TPC-H Delta source. Each block
# returns a Spark DataFrame ready to write as plain Delta.
#
# These projections follow the SSB paper's "Table 1: Schema Mapping"
# (O'Neil et al., 2009, Section 4). They are the canonical derivation
# used by every published SSB-on-Delta fixture.
_DDL = {
    "date": """
        SELECT
            cast(date_format(d, 'yyyyMMdd') as int) AS d_datekey,
            date_format(d, 'MMMM d, yyyy')         AS d_date,
            date_format(d, 'EEEE')                 AS d_dayofweek,
            date_format(d, 'MMMM')                 AS d_month,
            year(d)                                AS d_year,
            year(d) * 10 + quarter(d)              AS d_yearmonthnum,
            year(d) * 100 + month(d)               AS d_yearmonth,
            dayofyear(d)                           AS d_daynuminyear,
            dayofmonth(d)                          AS d_daynuminmonth,
            cast(weekofyear(d) as int)             AS d_daynuminweek,
            cast(weekofyear(d) as int)             AS d_weeknuminyear,
            'Spring'                               AS d_sellingseason,
            cast(dayofweek(d) > 1
                 and dayofweek(d) < 7 as int)      AS d_lastdayinweekfl,
            cast(d = last_day(d) as int)           AS d_lastdayinmonthfl,
            cast(dayofweek(d) in (1, 7) as int)    AS d_holidayfl,
            cast(dayofweek(d) > 1
                 and dayofweek(d) < 7 as int)      AS d_weekdayfl
        FROM (
            SELECT explode(sequence(date '1992-01-01',
                                    date '1998-12-31',
                                    interval 1 day)) AS d
        )
    """,

    "part": """
        SELECT
            p_partkey,
            p_name,
            p_mfgr,
            element_at(split(p_type, ' '), 1) AS p_category,
            p_brand,
            element_at(split(p_type, ' '), -1) AS p_color,
            p_type,
            p_size,
            p_container
        FROM tpch_part
    """,

    "supplier": """
        SELECT
            s_suppkey,
            s_name,
            s_address,
            cast(substr(n_name, 1, 9) as string) AS s_city,
            n_name                                AS s_nation,
            r_name                                AS s_region,
            s_phone
        FROM tpch_supplier s
        JOIN tpch_nation  n ON s.s_nationkey = n.n_nationkey
        JOIN tpch_region  r ON n.n_regionkey = r.r_regionkey
    """,

    "customer": """
        SELECT
            c_custkey,
            c_name,
            c_address,
            cast(substr(n_name, 1, 9) as string) AS c_city,
            n_name                                AS c_nation,
            r_name                                AS c_region,
            c_phone,
            c_mktsegment
        FROM tpch_customer c
        JOIN tpch_nation  n ON c.c_nationkey = n.n_nationkey
        JOIN tpch_region  r ON n.n_regionkey = r.r_regionkey
    """,

    "lineorder": """
        SELECT
            l_orderkey                         AS lo_orderkey,
            l_linenumber                       AS lo_linenumber,
            o_custkey                          AS lo_custkey,
            l_partkey                          AS lo_partkey,
            l_suppkey                          AS lo_suppkey,
            cast(date_format(o_orderdate, 'yyyyMMdd') as int) AS lo_orderdate,
            o_orderpriority                    AS lo_orderpriority,
            o_shippriority                     AS lo_shippriority,
            cast(l_quantity as int)            AS lo_quantity,
            cast(l_extendedprice as int)       AS lo_extendedprice,
            cast(l_extendedprice * l_quantity as int) AS lo_ordtotalprice,
            cast(l_discount * 100 as int)      AS lo_discount,
            cast(l_extendedprice * (1 - l_discount) as int) AS lo_revenue,
            cast(l_extendedprice * (1 - l_discount)
                 - ps_supplycost * l_quantity as int) AS lo_supplycost,
            cast(l_tax * 100 as int)           AS lo_tax,
            cast(date_format(l_commitdate, 'yyyyMMdd') as int) AS lo_commitdate,
            l_shipmode                         AS lo_shipmode
        FROM tpch_lineitem  l
        JOIN tpch_orders    o  ON l.l_orderkey = o.o_orderkey
        JOIN tpch_partsupp  ps ON l.l_partkey  = ps.ps_partkey
                              AND l.l_suppkey  = ps.ps_suppkey
    """,
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scale", type=int, default=1,
                        help="Source TPC-H scale factor; writes ssb_sf<N>_delta/.")
    parser.add_argument("--data-dir", default=str(_REPO_ROOT / "data"),
                        help="Bench data root.")
    parser.add_argument("--overwrite", action="store_true",
                        help="Delete and recreate the Delta directory if it exists.")
    args = parser.parse_args()

    data_root = Path(args.data_dir)
    src_dir = data_root / f"tpch_sf{args.scale}_delta"
    dst_dir = data_root / f"ssb_sf{args.scale}_delta"
    stage_dir = data_root / f"ssb_sf{args.scale}"  # parquet stage for preflight

    for t in ("lineitem", "orders", "partsupp", "customer", "supplier",
              "nation", "region", "part"):
        if not (src_dir / t).exists():
            print(f"ERROR: missing TPC-H source: {src_dir / t}", file=sys.stderr)
            print("Run data_gen/generate_tpch_delta.py first.", file=sys.stderr)
            return 1

    sys.path.insert(0, str(_REPO_ROOT))
    from engines._spark_session import get_spark  # type: ignore

    spark = get_spark()
    spark.conf.set("spark.databricks.delta.properties.defaults.enableDeletionVectors", "false")
    spark.conf.set("spark.databricks.delta.properties.defaults.columnMapping.mode", "none")
    spark.conf.set("spark.databricks.delta.properties.defaults.enableRowTracking", "false")

    # Register TPC-H source tables as temp views with the `tpch_` prefix
    # so the SSB-from-TPCH SELECTs don't collide with the SSB output names
    # (e.g. SSB's `supplier` vs TPC-H's `supplier`).
    for t in ("lineitem", "orders", "partsupp", "customer", "supplier",
              "nation", "region", "part"):
        spark.read.format("delta").load(str(src_dir / t)).createOrReplaceTempView(f"tpch_{t}")

    dst_dir.mkdir(parents=True, exist_ok=True)
    stage_dir.mkdir(parents=True, exist_ok=True)
    plain_props = (
        "TBLPROPERTIES ("
        "'delta.enableDeletionVectors' = 'false',"
        "'delta.columnMapping.mode'    = 'none',"
        "'delta.enableRowTracking'     = 'false'"
        ")"
    )

    for t in SSB_TABLES:
        dst = dst_dir / t
        if dst.exists():
            if args.overwrite:
                shutil.rmtree(dst)
            else:
                print(f"[skip] {dst} already exists; pass --overwrite to recreate")
                continue

        t0 = time.perf_counter()
        spark.sql(
            f"CREATE OR REPLACE TABLE delta.`{dst}` USING DELTA {plain_props} "
            f"AS {_DDL[t].strip()}"
        )
        n = spark.read.format("delta").load(str(dst)).count()
        print(f"[wrote] {t:<10} rows={n:>13,} elapsed={time.perf_counter() - t0:.2f}s")

    # Pre-flight expects parquet under data_subdir; stamp a single parquet
    # next to the Delta dir so bench_runner's `any(d.rglob('*.parquet'))`
    # check passes. The bench reads from <dst_dir>, never from this file.
    stamp = stage_dir / "_marker.parquet"
    if not stamp.exists():
        spark.range(1).write.parquet(str(stamp))
        print(f"[stamp] {stamp} (pre-flight marker)")

    spark.stop()
    print(f"\n[done] SSB plain Delta tables under {dst_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
