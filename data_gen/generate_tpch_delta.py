"""Convert the TPC-H parquet fixture into plain Delta tables.

Run once per bench host (output persists across bench runs). The output
directory is /workspace/data/tpch_sf{scale}_delta/<table>/. Every table
is written with NO Delta protocol upgrades:

  - delta.enableDeletionVectors = false        (no DV)
  - delta.columnMapping.mode    = none         (no rename / drop column)
  - delta.enableRowTracking     = false        (no row IDs in metadata)
  - delta.feature.*             = not set      (no preview features)

The point of "plain Delta" is so DuckDB's delta extension (read-only,
supports only the baseline protocol) can read these tables in the same
bench. With special features enabled the comparison would be unfair to
DuckDB and the leaderboard would mix engines reading different formats.

Source: the parquet files generated by data_gen/generate_tpch.py at
/workspace/data/tpch_sf{scale}/<table>.parquet. Re-run that script
first if those files are missing.

Usage (inside the bench container):
    python data_gen/generate_tpch_delta.py --scale 1
"""
from __future__ import annotations

import argparse
import os
import shutil
import sys
import time
from pathlib import Path


# Repo root, resolved from THIS file's location so the benchmark runs on any
# host (the container historically used WORKDIR=/workspace; off-container that
# path does not exist). data_gen/<file>.py -> parent.parent == repo root.
_REPO_ROOT = Path(__file__).resolve().parent.parent

TABLES = [
    "region", "nation", "supplier", "customer",
    "part", "partsupp", "orders", "lineitem",
]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scale", type=int, default=1,
                        help="TPC-H scale factor; reads tpch_sf<N>/, writes tpch_sf<N>_delta/.")
    parser.add_argument("--data-dir", default=str(_REPO_ROOT / "data"),
                        help="Bench data root.")
    parser.add_argument("--overwrite", action="store_true",
                        help="Delete and recreate the Delta directory if it already exists.")
    args = parser.parse_args()

    src_dir = Path(args.data_dir) / f"tpch_sf{args.scale}"
    dst_dir = Path(args.data_dir) / f"tpch_sf{args.scale}_delta"
    for t in TABLES:
        if not (src_dir / f"{t}.parquet").exists():
            print(f"ERROR: source parquet missing: {src_dir/f'{t}.parquet'}",
                  file=sys.stderr)
            return 1

    # Re-use the bench's Spark builder so the session config matches the
    # engine adapter under test.
    sys.path.insert(0, str(_REPO_ROOT))
    from engines._spark_session import get_spark  # type: ignore

    spark = get_spark()
    # Plain-Delta defaults at the session level. The per-write TBLPROPERTIES
    # below are belt-and-braces; the session config is the wider safety net
    # for any spark.sql / DataFrame writer in this script that does not
    # forward properties explicitly.
    spark.conf.set("spark.databricks.delta.properties.defaults.enableDeletionVectors", "false")
    spark.conf.set("spark.databricks.delta.properties.defaults.columnMapping.mode", "none")
    spark.conf.set("spark.databricks.delta.properties.defaults.enableRowTracking", "false")

    dst_dir.mkdir(parents=True, exist_ok=True)
    plain_props = (
        "TBLPROPERTIES ("
        "'delta.enableDeletionVectors' = 'false',"
        "'delta.columnMapping.mode'    = 'none',"
        "'delta.enableRowTracking'     = 'false'"
        ")"
    )

    for t in TABLES:
        src = src_dir / f"{t}.parquet"
        dst = dst_dir / t
        if dst.exists():
            if args.overwrite:
                print(f"[overwrite] rm -rf {dst}")
                shutil.rmtree(dst)
            else:
                print(f"[skip] {dst} already exists; pass --overwrite to recreate")
                continue

        # Read source parquet into a Spark DataFrame, then write as Delta.
        # CREATE TABLE ... USING DELTA OPTIONS (path '...') AS SELECT * FROM source
        # is the simplest way to apply TBLPROPERTIES at write time without
        # going through the DataFrameWriter API (which would not let us set
        # all three props at once on Delta < 3.0 in some configurations).
        view = f"src_{t}"
        spark.read.parquet(str(src)).createOrReplaceTempView(view)

        t0 = time.perf_counter()
        spark.sql(
            f"CREATE OR REPLACE TABLE delta.`{dst}` USING DELTA {plain_props} "
            f"AS SELECT * FROM {view}"
        )
        dt = time.perf_counter() - t0
        # Sanity: count the rows back via Spark on the new Delta directory.
        n = spark.read.format("delta").load(str(dst)).count()
        print(f"[wrote] {dst}  rows={n:>10,}  elapsed={dt:.2f}s")

    spark.stop()
    print(f"\n[done] Delta tables under {dst_dir}")
    print("Verify protocol features look clean:")
    print(f"  cat {dst_dir}/lineitem/_delta_log/00000000000000000000.json | head -3")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
